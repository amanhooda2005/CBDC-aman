# ===================================================================== model, input, calibration
def shape_of(st):
    if st["inputs"] == [-1]:
        return "proj"
    if len(st["inputs"]) > 1:
        return "join"
    return "head" if st["kind"] == "head" else "block"


def load_input(data_dir, seed=0):
    spec = json.load(open(HERE.parent / "h4-pqc-stark/zk_composed/specs/h1_spec.json"))
    box_lo, box_hi = np.array(spec["x_lo"]) / 2 ** spec["ax"], np.array(spec["x_hi"]) / 2 ** spec["ax"]
    rng = np.random.default_rng(seed)
    calib = np.clip(rng.normal(0, 1, (15, len(box_lo))), box_lo, box_hi)
    if data_dir:
        sys.path.insert(0, str(HERE))
        from data import apply_scaler, load, temporal_split
        m = pickle.load(open(HERE / "models/W32_B1.pkl", "rb"))
        X, y, ts = load(data_dir)
        _, _, (Xte, yte), _ = temporal_split(X, y, ts)
        Xte = apply_scaler(Xte, m["scaler"])
        i = int(rng.choice(np.where(yte == 1)[0]))   # a random illicit test transaction (seeded)
        x = Xte[i:i + 1].astype(np.float64)
        calib = Xte[rng.choice(len(Xte), 15, replace=False)].astype(np.float64)
        return x, np.vstack([x, calib]), {"source": "Elliptic test period", "index_in_test": i, "label_illicit": int(yte[i])}
    x = (np.array(spec["x"]) / 2 ** spec["ax"]).reshape(1, -1)
    return x, np.vstack([x, calib]), {"source": "H4 spec example (Elliptic test period, quantized at 8 bits)",
                                      "index_in_test": spec["example_index_in_test"], "label_illicit": spec["example_label"]}


# ===================================================================== setup: shared circuits + verifiers
def run_args(shape):
    ra = ezkl.PyRunArgs()
    ra.input_visibility = "public" if shape == "proj" else "hashed"
    ra.output_visibility = "public" if shape == "head" else "hashed"
    ra.param_visibility = "hashed"
    ra.input_scale = S
    ra.param_scale = S
    ra.num_inner_cols = 4 if shape == "proj" else 2
    ra.decomp_base = 256
    ra.decomp_legs = 4
    return ra


def step_onnx(st, path, in_dims):
    if len(st["inputs"]) > 1:
        build_join_block(st["unit"], in_dims, path)
    else:
        build([st["unit"]], path)


def write_inputs(path, arrays):
    json.dump({"input_data": [deq(a).reshape(-1).tolist() for a in arrays]}, open(path, "w"))


async def make_sol(d, srs):
    try:   # writes Verifier.sol, then tries to fetch solc for the ABI (blocked offline) -> ignore
        await ezkl.create_evm_verifier(f"{d}/vk.key", f"{d}/settings.json", f"{d}/Verifier.sol", f"{d}/Verifier.abi", srs, False)
    except RuntimeError:
        pass
    assert os.path.exists(f"{d}/Verifier.sol")


def setup(steps, calib_q, wd):
    """calib_q: (xq, outs) of the calibration batch. Returns the manifest (cached)."""
    mpath = wd / "manifest.json"
    if mpath.exists():
        return json.load(open(mpath))
    xq_c, outs_c = calib_q
    groups = {}
    for k, st in enumerate(steps):
        groups.setdefault(shape_of(st), []).append(k)
    man = {"groups": {}, "steps": []}
    for shape, ks in groups.items():
        d = wd / shape
        d.mkdir(parents=True, exist_ok=True)
        rep = steps[ks[0]]
        cins = [xq_c if j == -1 else outs_c[j] for j in rep["inputs"]]
        in_dims = [a.shape[1] for a in cins]
        step_onnx(rep, str(d / "rep.onnx"), in_dims)
        write_inputs(str(d / "calib.json"), cins)
        t = time.time()
        assert ezkl.gen_settings(str(d / "rep.onnx"), str(d / "settings.json"), py_run_args=run_args(shape))
        ezkl.calibrate_settings(str(d / "calib.json"), str(d / "rep.onnx"), str(d / "settings.json"), "resources",
                                scales=[S], scale_rebase_multiplier=[1])
        logrows = json.load(open(d / "settings.json"))["run_args"]["logrows"]
        srs = wd / f"srs_{logrows}.srs"
        if not srs.exists():
            ezkl.gen_srs(str(srs), logrows)
        assert ezkl.compile_circuit(str(d / "rep.onnx"), str(d / "rep.compiled"), str(d / "settings.json"))
        assert ezkl.setup(str(d / "rep.compiled"), str(d / "vk.key"), str(d / "pk.key"), srs_path=str(srs))
        setup_s = time.time() - t
        asyncio.run(make_sol(str(d), str(srs)))
        man["groups"][shape] = {"dir": str(d), "logrows": logrows, "srs": str(srs), "steps": ks, "setup_s": setup_s,
                                "pk_mb": os.path.getsize(d / "pk.key") / 1e6}
        print(f"setup {shape}: {len(ks)} steps, logrows {logrows}, {setup_s:.1f} s", flush=True)
    for k, st in enumerate(steps):
        shape = shape_of(st)
        d = Path(man["groups"][shape]["dir"])
        cins = [xq_c[:1] if j == -1 else outs_c[j][:1] for j in st["inputs"]]
        onnx_p, comp = str(d / f"s{k}.onnx"), str(d / f"s{k}.compiled")
        step_onnx(st, onnx_p, [a.shape[1] for a in cins])
        assert ezkl.compile_circuit(onnx_p, comp, str(d / "settings.json"))
        write_inputs(str(d / f"s{k}_probe.json"), cins)
        ezkl.gen_witness(str(d / f"s{k}_probe.json"), comp, str(d / f"s{k}_probe_w.json"))
        ph = json.load(open(d / f"s{k}_probe_w.json"))["processed_params"]["poseidon_hash"][0]
        man["steps"].append({"k": k, "name": st["name"], "shape": shape, "compiled": comp, "param_hash": "0x" + felt_b32(ph).hex()})
    json.dump(man, open(mpath, "w"), indent=1)
    return man


# ===================================================================== chain helpers
class Chain:
    def __init__(self, record=None):
        self.w3 = Web3(Web3.HTTPProvider(RPC, request_kwargs={"timeout": 120}))
        self.acct = {n: Account.from_key(k) for n, k in KEYS.items()}
        self.log = open(Path(record) / "transactions.jsonl", "a") if record else None
        # signed transactions + block timestamps: lets anyone rebuild the chain with any Foundry version
        self.raw = open(Path(record) / "raw_transactions.jsonl", "a") if record else None
        self.context = ""

    def _record(self, who, fn, rc, tx_hash, raw=None):
        if self.raw is not None and raw is not None:
            self.raw.write(json.dumps({"tx": "0x" + bytes(tx_hash).hex(), "block": rc.blockNumber, "raw": "0x" + bytes(raw).hex(),
                                       "timestamp": self.w3.eth.get_block(rc.blockNumber).timestamp}) + "\n")
            self.raw.flush()
        if self.log:
            name = "deploy" if fn is None else fn.fn_name
            self.log.write(json.dumps({"scenario": self.context, "who": who, "function": name, "tx": "0x" + bytes(tx_hash).hex(),
                                       "block": rc.blockNumber, "status": rc.status, "gas": rc.gasUsed,
                                       "contract": rc.contractAddress or rc.to}) + "\n")
            self.log.flush()

    def send(self, who, fn=None, *, deploy=None, value=0, gas=25_000_000):
        a = self.acct[who]
        base = {"from": a.address, "nonce": self.w3.eth.get_transaction_count(a.address), "value": value, "gas": gas,
                "gasPrice": self.w3.eth.gas_price, "chainId": self.w3.eth.chain_id}
        tx = (self.w3.eth.contract(abi=deploy[0], bytecode=deploy[1]).constructor(*deploy[2]) if deploy else fn).build_transaction(base)
        raw = a.sign_transaction(tx).raw_transaction
        h = self.w3.eth.send_raw_transaction(raw)
        rc = self.w3.eth.wait_for_transaction_receipt(h)
        self._record(who, fn, rc, h, raw)
        return rc

    def must(self, who, fn, **kw):
        rc = self.send(who, fn, **kw)
        assert rc.status == 1, rc
        return rc


def solc(sol_path):
    out = subprocess.run([SOLC, "--combined-json", "abi,bin", "--optimize", "--optimize-runs", "1", sol_path],
                         capture_output=True, text=True, check=True).stdout
    c = json.loads(out)["contracts"]
    name = next(n for n in c if n.endswith(":Halo2Verifier")) if any(n.endswith(":Halo2Verifier") for n in c) else next(iter(c))
    abi = c[name]["abi"]
    return (json.loads(abi) if isinstance(abi, str) else abi), c[name]["bin"]


def artifact(name):
    a = json.load(open(HERE / f"out/{name}.sol/{name}.json"))
    return a["abi"], a["bytecode"]["object"]


# ===================================================================== traces and commitments
def commit_trace(outs, garbage_at=None):
    leaves = [felt_b32(leaf(o[0])) for o in outs[:-1]] + [head_leaf(outs[-1][0])]
    P, acc = [], chain.ZERO
    for i, l in enumerate(leaves):
        acc = chain.k256(b"garbage") if i == garbage_at else chain.k256(acc + l)
        P.append(acc)
    lv = chain.merkle_levels(leaves, P)
    return {"leaves": leaves, "P": P, "levels": lv, "root": lv[-1][0]}


def corrupt_fn(step, n):
    def f(o):
        if step == n - 1:
            o[0, 0] = -o[0, 0] if o[0, 0] != 0 else 2 ** S
        else:
            o[0, int(np.argmax(o[0]))] += 3 * 2 ** S
        return o
    return f


def prove_step(man, k, inputs, wd, tag, compiled_override=None):
    st = man["steps"][k]
    g = man["groups"][st["shape"]]
    d = Path(g["dir"])
    inp, wit, prf = wd / f"{tag}_in.json", wd / f"{tag}_w.json", wd / f"{tag}_proof.json"
    write_inputs(str(inp), inputs)
    comp = compiled_override or st["compiled"]
    t = time.time()
    ezkl.gen_witness(str(inp), comp, str(wit))
    assert ezkl.prove(str(wit), comp, str(d / "pk.key"), str(prf), srs_path=g["srs"])
    prove_s = time.time() - t
    ok = ezkl.verify(str(prf), str(d / "settings.json"), str(d / "vk.key"), srs_path=g["srs"])
    cd = bytes(ezkl.encode_evm_calldata(str(prf), str(wd / f"{tag}_calldata.bytes")))
    if RECORD:   # the exact verifyProof calldata, so anyone can re-run the verifier on the recorded chain state
        (Path(RECORD) / "proofs").mkdir(exist_ok=True)
        shutil.copy(wd / f"{tag}_calldata.bytes", Path(RECORD) / "proofs" / f"{tag}_verifyProof_calldata.bin")
        shutil.copy(prf, Path(RECORD) / "proofs" / f"{tag}_proof.json")
    proof_bytes, instances = abi_decode(["bytes", "uint256[]"], cd[4:])
    return proof_bytes, list(instances), {"prove_s": prove_s, "verified_offchain": bool(ok), "proof_bytes": len(proof_bytes)}


# ===================================================================== one game
SCENARIOS = [
    dict(name="asserter cheats at a projection step", cheat="asserter", step=0),
    dict(name="asserter cheats at the join step", cheat="asserter", step=2),
    dict(name="asserter cheats at a middle block", cheat="asserter", step=30),
    dict(name="asserter cheats at the head (the decision)", cheat="asserter", step=-1),
    dict(name="false challenge against an honest asserter", cheat="challenger", step=33),
    dict(name="malformed prefix chain (honest leaf at the disputed step)", cheat="asserter_malformed_chain", step=40),
    dict(name="attack: valid proof made with another block's weights", cheat="asserter", step=20, wrong_weights=True),
]


def play(ch, game, man, steps, x, sc, wd, sid):
    n = len(steps)
    k_cheat = sc["step"] % n
    malformed = sc["cheat"] == "asserter_malformed_chain"
    xq, honest = run_steps(steps, x)
    _, bad = run_steps(steps, x, corrupt=(k_cheat + 1 if malformed else k_cheat, corrupt_fn(k_cheat + 1 if malformed else k_cheat, n)))
    A_outs, C_outs = (honest, bad) if sc["cheat"] == "challenger" else (bad, honest)
    A = commit_trace(A_outs, garbage_at=k_cheat if malformed else None)
    C = commit_trace(C_outs)
    in_felts = [felt_int(f) for f in [ezkl.float_to_felt(float(v) / 2 ** S, S) for v in xq[0]]]
    inp_hash = chain.input_hash(in_felts)
    out_digest = A["leaves"][-1]
    g, asr, chl = {}, ch.acct["asserter"].address, ch.acct["challenger"].address
    rc = ch.must("asserter", game.functions.commit(A["root"], out_digest, inp_hash))
    g["commit"] = rc.gasUsed
    cid = game.functions.nClaims().call() - 1
    ts = ch.w3.eth.get_block(rc.blockNumber).timestamp
    claim = (A["root"], out_digest, inp_hash, asr, ts)
    g["challenge"] = ch.must("challenger", game.functions.challenge(cid, claim), value=CBOND).gasUsed
    did = game.functions.disputeId(cid, chl).call()
    pf = lambda T, i: chain.merkle_proof(T["levels"], i)
    rc = ch.send("asserter", game.functions.openFinal(did, claim, A["leaves"][n - 1], A["P"][n - 1], pf(A, n - 1),
                                                      A["leaves"][n - 2], A["P"][n - 2], pf(A, n - 2)))
    g["openFinal"] = rc.gasUsed
    g["reveal"], g["respond"] = [], []
    rounds = 0
    while True:
        phase, lo1, hi, _ = game.functions.status(did).call()
        if phase == 2:
            mid = game.functions.currentMid(did).call()
            g["reveal"].append(ch.must("asserter", game.functions.reveal(did, mid, A["leaves"][mid], A["P"][mid], pf(A, mid))).gasUsed)
            rounds += 1
        elif phase == 3:
            mid = game.functions.currentMid(did).call()
            g["respond"].append(ch.must("challenger", game.functions.respond(did, A["P"][mid] == C["P"][mid])).gasUsed)
        else:
            break
    phase, lo1, hi, _ = game.functions.status(did).call()
    res = dict(scenario=sc["name"], cheat=sc["cheat"], cheated_step=k_cheat, n_steps=n, bisection_rounds=rounds,
               found_step=hi, located_correctly=hi == k_cheat)
    if phase in (5, 6):   # decided during bisection (malformed chain)
        res.update(winner="asserter" if phase == 5 else "challenger", decided_by="prefix-chain consistency check, no proof",
                   gas=g)
    else:
        assert phase == 4, phase
        k = hi
        # agreed inputs of step k and their openings back to the agreed prefix
        ins = [xq if j == -1 else C_outs[j] for j in steps[k]["inputs"]]
        ops = []
        for j in steps[k]["inputs"]:
            if j >= 0:
                ops.append((chain.ZERO if j == 0 else A["P"][j - 1], A["leaves"][j:k]))
        if sc.get("wrong_weights"):
            # a VALID proof of the same-shape step k+1 (other weights) on step k's agreed inputs:
            # the shared verifier accepts it; the game must refuse it on the weight-hash instance
            proof, inst, pinfo = prove_step(man, k, ins, wd, f"s{sid}_wrong", man["steps"][k + 1]["compiled"])
            try:
                game.functions.resolve(did, claim, proof, inst, ops).call({"from": asr})
                res["wrong_weights_proof"] = "ACCEPTED (unsound)"
            except Exception as e:
                msg = str(e)
                res["wrong_weights_proof"] = {"verified_offchain": pinfo["verified_offchain"],
                                              "rejected_onchain": msg[msg.find("params"):][:60] if "params" in msg else msg[:120]}
                if RECORD:   # also put the rejected attempt on the chain, so it is visible as a reverted transaction
                    rc = ch.send("asserter", game.functions.resolve(did, claim, proof, inst, ops), gas=15_000_000)
                    res["wrong_weights_proof"]["onchain_tx_status"] = rc.status
        proof, inst, pinfo = prove_step(man, k, ins, wd, f"s{sid}")
        res.update(step_name=steps[k]["name"], shape=man["steps"][k]["shape"], n_instances=len(inst), **pinfo)
        fn = game.functions.resolve(did, claim, proof, inst, ops)
        fn.call({"from": chl})          # surfaces the revert reason, if any
        rc = ch.must("challenger", fn)
        g["resolve"] = rc.gasUsed
        phase = game.functions.status(did).call()[0]
        ev = game.events.Resolved().process_receipt(rc)
        res.update(winner="asserter" if phase == 5 else "challenger", decided_by=ev[0]["args"]["reason"] if ev else "?", gas=g)
    honest_side = "asserter" if sc["cheat"] == "challenger" else "challenger"
    res["outcome_correct"] = res["winner"] == honest_side and (
        not sc.get("wrong_weights") or "step weights" in str(res.get("wrong_weights_proof")))
    g["game_total"] = g["challenge"] + g["openFinal"] + sum(g["reveal"]) + sum(g["respond"]) + g.get("resolve", 0)
    return res


def main():
    ap = argparse.ArgumentParser()
    ap.add_argument("--blocks", type=int, default=60)
    ap.add_argument("--data", default=None)
    ap.add_argument("--scenarios", default=",".join(str(i) for i in range(len(SCENARIOS))))
    ap.add_argument("--record", default=None, help="directory for transactions.jsonl, raw_transactions.jsonl, proofs/ and anvil_state.json")
    a = ap.parse_args()
    global RECORD
    if a.record:
        RECORD = str(Path(a.record).resolve())
        Path(RECORD).mkdir(parents=True, exist_ok=True)
    wd = HERE / f"work/onchain_S{a.blocks}"
    wd.mkdir(parents=True, exist_ok=True)
    m = pickle.load(open(HERE / f"models/W32_B{a.blocks}.pkl", "rb"))
    steps = quantize_steps(dispute_steps(m["units"]))
    x, calib, src = load_input(a.data)
    man = setup(steps, run_steps(steps, calib), wd)

    dump = ["--dump-state", str(Path(RECORD) / "anvil_state.json")] if RECORD else []
    anvil = subprocess.Popen([f"{BIN}/anvil", "--port", str(PORT), "--code-size-limit", "1000000", "--gas-limit", "300000000", "--silent", *dump])
    time.sleep(2)
    try:
        ch = Chain(RECORD)
        out = {"model": f"W32_B{a.blocks}", "n_steps": len(steps), "input": src, "verifiers": {}, "scenarios": {}}
        vaddr = {}
        for shape, gr in man["groups"].items():
            abi, code = solc(gr["dir"] + "/Verifier.sol")
            rc = ch.must("deployer", None, deploy=(abi, code, []), gas=60_000_000)
            vaddr[shape] = rc.contractAddress
            out["verifiers"][shape] = {"steps_served": len(gr["steps"]), "logrows": gr["logrows"], "deploy_gas": rc.gasUsed,
                                       "bytecode_kb": len(code) / 2 / 1024, "setup_s": gr["setup_s"], "pk_mb": gr["pk_mb"]}
        gabi, gcode = artifact("OptimisticInferenceV2")
        params = (len(x[0]), [vaddr[s["shape"]] for s in man["steps"]], [bytes.fromhex(s["param_hash"][2:]) for s in man["steps"]],
                  [st["inputs"] for st in steps], ABOND, CBOND, 86400, 3600, 172800)
        rc = ch.must("deployer", None, deploy=(gabi, gcode, [params]), gas=60_000_000)
        game = ch.w3.eth.contract(address=rc.contractAddress, abi=gabi)
        out["game_deploy_gas"] = rc.gasUsed
        out["verifier_deploy_gas_total"] = sum(v["deploy_gas"] for v in out["verifiers"].values())
        ch.must("asserter", game.functions.depositBond(), value=20 * 10**18)
        for sid in [int(s) for s in a.scenarios.split(",")]:
            ch.context = str(sid)
            r = play(ch, game, man, steps, x, SCENARIOS[sid], wd, sid)
            r["dispute_id"] = "0x" + bytes(game.functions.disputeId(game.functions.nClaims().call() - 1, ch.acct["challenger"].address).call()).hex()
            out["scenarios"][str(sid)] = r
            print(json.dumps({k: v for k, v in r.items() if k != "gas"}), "| game gas", r["gas"]["game_total"], flush=True)
        out["all_correct"] = all(r["outcome_correct"] for r in out["scenarios"].values())
        if not RECORD:   # a recorded re-run goes to its own folder and leaves the committed result files alone
            json.dump(out, open(HERE / f"results/onchain_disputes_B{a.blocks}{'_elliptic' if a.data else ''}.json", "w"), indent=2, default=str)
        print("all outcomes correct:", out["all_correct"])
        if RECORD:
            out["contracts"] = {"game": game.address, "verifiers": vaddr}
            json.dump(out, open(Path(RECORD) / "result.json", "w"), indent=2, default=str)
    finally:
        anvil.send_signal(signal.SIGINT)   # graceful stop, so --dump-state writes the chain state
        try:
            anvil.wait(60)
        except subprocess.TimeoutExpired:
            anvil.kill()


if __name__ == "__main__":
    main()
