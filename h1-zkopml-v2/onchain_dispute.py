"""Full on-chain dispute games with REAL EZKL step verifiers (no mock), one shared verifier per step shape.

Setup (cached in work/onchain_S{B}/):
  - the B-block model is split into its bisectable steps (proj0, proj1, join, blocks, head);
  - steps with the same shape share ONE circuit: weights are a hashed public instance
    (EZKL param_visibility = "hashed"), so 4 verifiers serve all 63 steps of the 60-block model
    instead of 63 step-specific ones; the game contract stores each step's weight hash and rejects a
    proof whose weight-hash instance is not that step's (OptimisticInferenceV2._checkParams);
  - one Solidity verifier per shape is generated by EZKL and compiled with solc.
Games (local anvil chain; gas is chain-independent):
  commit -> challenge -> openFinal -> bisection (reveal / respond) -> resolve with one real step proof.
Scenarios: a cheating asserter at a projection, join, block and head step; a false challenge against an
honest asserter; a malformed prefix chain; and an attack the shared verifier must stop (a valid proof
made with another block's weights).

Input: one Elliptic test-period transaction. With --data (folder with X.npy, y.npy, ts.npy from
prepare_data.py) a labelled test transaction is used; without it, the H4 specification's example
transaction (an illicit test-period transaction, stored quantized at 8 fractional bits) is used.

Usage: python3 onchain_dispute.py [--blocks 60] [--data DIR] [--scenarios 0,1,2,...]
Writes results/onchain_disputes_B{B}.json (with --data: ..._elliptic.json)
"""
